// Embeds the per-coat scroll rope-climb sprite frames into a generated
// src/climb-frames.js as base64 data URLs, so the renderer can blit them with no
// runtime file I/O (contextIsolation is on) and no packaging/asar path issues.
//
// Layout: assets/climb/<coat-slug>/{idle,up1,up2,down1,down2}.png
//   e.g. assets/climb/tuxedo/, assets/climb/orange-tabby/
// 'tuxedo' is the default set every coat without its own frames falls back to.
// Add a coat with: node scripts/slice-climb-sheet.js <sheet.png> <coat-slug>
// Then run: npm run climb-frames
const fs = require('fs');
const path = require('path');

const FRAMES = ['idle', 'up1', 'up2', 'down1', 'down2'];
const climbDir = path.join(__dirname, '..', 'assets', 'climb');
const outFile = path.join(__dirname, '..', 'src', 'climb-frames.js');

// each coat = a subdirectory of assets/climb/ (skip _sheets and dotfiles)
const coats = fs.existsSync(climbDir)
  ? fs.readdirSync(climbDir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && !e.name.startsWith('_') && !e.name.startsWith('.'))
      .map((e) => e.name)
  : [];

const coatBlocks = [];
let totalFrames = 0;
for (const coat of coats) {
  const frames = [];
  for (const name of FRAMES) {
    const p = path.join(climbDir, coat, `${name}.png`);
    if (!fs.existsSync(p)) continue;
    const b64 = fs.readFileSync(p).toString('base64');
    frames.push(`    ${name}: 'data:image/png;base64,${b64}'`);
    totalFrames++;
  }
  if (frames.length) {
    coatBlocks.push(`  ${JSON.stringify(coat)}: {\n${frames.join(',\n')}\n  }`);
    console.log(`  ${coat}: ${frames.length} frame(s)`);
  }
}

const body = coatBlocks.length
  ? `// AUTO-GENERATED by scripts/embed-climb-frames.js - do not edit by hand.\n` +
    `// Per-coat rope-climb sprite frames as data URLs (see assets/climb/<coat>/*.png).\n` +
    `var CLIMB_FRAMES = {\n${coatBlocks.join(',\n')}\n};\n`
  : `// AUTO-GENERATED by scripts/embed-climb-frames.js - no coat folders found in assets/climb/.\n` +
    `var CLIMB_FRAMES = {};\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body);
console.log(`wrote src/climb-frames.js (${coatBlocks.length} coat(s), ${totalFrames} frame(s))`);
