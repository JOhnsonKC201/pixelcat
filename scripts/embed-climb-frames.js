// Embeds the scroll rope-climb sprite frames (assets/climb/*.png) into a generated
// src/climb-frames.js as base64 data URLs, so the renderer can blit them with no
// runtime file I/O (contextIsolation is on) and no packaging/asar path issues.
// Drop the 5 PNGs into assets/climb/, then run: npm run climb-frames
const fs = require('fs');
const path = require('path');

const FRAMES = ['idle', 'up1', 'up2', 'down1', 'down2'];
const srcDir = path.join(__dirname, '..', 'assets', 'climb');
const outFile = path.join(__dirname, '..', 'src', 'climb-frames.js');

const entries = [];
for (const name of FRAMES) {
  const p = path.join(srcDir, `${name}.png`);
  if (!fs.existsSync(p)) { console.log(`  (skip ${name}.png — not found)`); continue; }
  const b64 = fs.readFileSync(p).toString('base64');
  entries.push(`  ${name}: 'data:image/png;base64,${b64}'`);
}

const body = entries.length
  ? `// AUTO-GENERATED by scripts/embed-climb-frames.js — do not edit by hand.\n` +
    `// Rope-climb sprite frames as data URLs (see assets/climb/*.png).\n` +
    `var CLIMB_FRAMES = {\n${entries.join(',\n')}\n};\n`
  : `// AUTO-GENERATED by scripts/embed-climb-frames.js — no frames found in assets/climb/.\n` +
    `var CLIMB_FRAMES = {};\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body);
console.log(`wrote src/climb-frames.js (${entries.length} frame${entries.length === 1 ? '' : 's'})`);
